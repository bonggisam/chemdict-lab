EXPS = []


def exp(id, level, course, area, title, summary, sensors, standards=(), std_texts=(), mode="time", interval=1000,
        event=None, steps=(), analysis=("stats", "fit"), materials=(), attach=(), cautions=(), textbooks=(),
        y=None, markers=("관찰 기록", "한 일 (예: 시약 넣음)"), parts=None, choose=False, breadboard=None):
    ys = []
    for s in sensors:
        lab, unit, lo, hi = Y[s]
        if y and s in y:
            lab, unit, lo, hi = y[s]
        d = {"sensor": s, "label": lab, "unit": unit}
        if lo is not None:
            d["min"] = lo
        if hi is not None:
            d["max"] = hi
        ys.append(d)
    pids = parts or list(dict.fromkeys(PART[s] for s in sensors))
    e = {
        "id": f"cur-{id}",
        "order": 100 + len(EXPS),
        "title": title,
        "subject": course,
        "level": level,
        "course": course,
        "area": area,
        "summary": summary,
        "standards": list(standards),
        "standardTexts": list(std_texts),
        "sensors": list(sensors),
        "mode": mode,
        "intervalMs": interval,
        "x": {"label": event["label"], "unit": event["unit"]} if event else {"label": "시간", "unit": "s"},
        "y": ys,
        "markers": {"enabled": mode == "time", "label": markers[0], "prompt": markers[1]},
        "analysis": list(analysis),
        "steps": list(steps),
        "setup": {"parts": pids, "choose": choose, "materials": list(materials), "attach": list(attach), "cautions": list(cautions)},
        "textbooks": [dict(publisher=p, course=c, note=n, sure=s) for (p, c, n, s) in textbooks],
    }
    if event:
        e["event"] = event
    # 브레드보드: 직접 지정하거나, 온도 센서를 여러 개 나란히 쓰는 실험이면 자동
    if not breadboard and TWO_T in attach:
        breadboard = ("recommended", "온도 센서 2개 이상을 같은 줄에 나란히 꽂습니다 (센서 1개면 필요 없음).", "pullup")
    if breadboard:
        e["breadboard"] = {"need": breadboard[0], "why": breadboard[1], "circuit": breadboard[2]}
    EXPS.append(e)


