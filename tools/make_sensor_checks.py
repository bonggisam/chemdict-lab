def main():
    sensors = json.loads((P / "sensors.json").read_text(encoding="utf-8"))
    types = {s["type"] for s in sensors["analog"] + sensors["digital"]}
    unknown = [k for k in list(CHECKS) + list(ALIASES) if k not in types]
    if unknown:
        raise SystemExit(f"sensors.json에 없는 type: {unknown}")
    bad = [k for k, v in ALIASES.items() if v not in CHECKS]
    if bad:
        raise SystemExit(f"별칭 대상이 없음: {bad}")
    for code, c in CHECKS.items():
        for r in c["refs"]:
            assert ("expect" in r and "tol" in r) or ("min" in r and "max" in r), (code, r)
    out = {
        "version": 1,
        "note": "센서 점검: 기준 상황(refs)은 point(expect±tol) 또는 range(min~max). 단위는 sensors.json의 단위. test = 정상 작동 확인 절차, fail = 고장 신호와 원인, errorNote = 오차를 읽는 법.",
        "bySensor": CHECKS,
        "aliases": ALIASES,
    }
    (P / "sensor_checks.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    covered = set(CHECKS) | set(ALIASES)
    print(f"sensor_checks.json: {len(CHECKS)} families, {len(ALIASES)} aliases; 미포함 type: {sorted(types - covered)}")


